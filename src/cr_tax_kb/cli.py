"""Command line: search, show a document, export the manifest, run the eval.

  python3 -m cr_tax_kb.cli search "¿cómo tributa la venta de bitcoin?" [-k 5] [--topic cripto] [--json]
  python3 -m cr_tax_kb.cli show crypto-assets
  python3 -m cr_tax_kb.cli list
  python3 -m cr_tax_kb.cli export        # writes data/index.json and data/chunks.jsonl
  python3 -m cr_tax_kb.cli eval [-k 3]
"""

import argparse
import json
import sys

from .corpus import REPO_ROOT, chunks_of
from .search import KnowledgeBase, format_hits


def export(kb, out=REPO_ROOT / "data"):
    out.mkdir(exist_ok=True)
    manifest = {
        "name": "cr-tax-kb",
        "description": "Costa Rica tax and accounting knowledge base",
        "documents": [d.summary() for d in kb.docs.values()],
    }
    (out / "index.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    with open(out / "chunks.jsonl", "w", encoding="utf-8") as f:
        for d in kb.docs.values():
            for c in chunks_of(d):
                row = {**c.__dict__, "as_of": d.as_of, "status": d.status, "verified": d.verified, "sources": d.sources}
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
    (REPO_ROOT / "llms.txt").write_text(llms_txt(kb), encoding="utf-8")
    return out


def llms_txt(kb):
    """llms.txt (https://llmstxt.org): a Markdown map of the repo for LLMs."""
    lines = [
        "# cr-tax-kb",
        "",
        "> Costa Rica tax and accounting knowledge base: IVA, income tax, capital gains, remittances abroad,"
        " crypto, e-invoicing v4.4, TRIBU-CR, simplified regime, CCSS, tax calendar. Every section cites its sources.",
        "",
        "Read AGENTS.md for how to answer and cite. Generated by `cr_tax_kb.cli export`; do not edit by hand.",
        "",
        "## Guides",
        "",
        "- [AGENTS.md](AGENTS.md): rules for answering from and editing this knowledge base",
        "- [SOURCES.md](SOURCES.md): source registry and known gaps",
        "",
    ]
    for topic in kb.topics():
        lines += [f"## {topic}", ""]
        for d in kb.docs.values():
            if d.topic == topic:
                lines.append(f"- [{d.title}]({d.path}): as of {d.as_of}, {d.status}, backed by {d.verified}")
        lines.append("")
    return "\n".join(lines)


def run_eval(kb, k=3):
    qs = json.loads((REPO_ROOT / "eval" / "questions.json").read_text(encoding="utf-8"))
    hits = 0
    for item in qs:
        got = [h["doc_id"] for h in kb.search(item["q"], k)]
        ok = item["expect"] in got
        hits += ok
        print(f"{'OK  ' if ok else 'MISS'} {item['q']} -> {got}")
    print(f"\nTop-{k} hit rate: {hits}/{len(qs)}")
    return hits, len(qs)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="cr-tax-kb")
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("search")
    s.add_argument("query")
    s.add_argument("-k", type=int, default=5)
    s.add_argument("--topic")
    s.add_argument("--json", action="store_true")
    sh = sub.add_parser("show")
    sh.add_argument("doc_id")
    sub.add_parser("list")
    sub.add_parser("export")
    e = sub.add_parser("eval")
    e.add_argument("-k", type=int, default=3)
    a = ap.parse_args(argv)
    kb = KnowledgeBase()
    if a.cmd == "search":
        hits = kb.search(a.query, a.k, a.topic)
        print(json.dumps(hits, ensure_ascii=False, indent=2) if a.json else format_hits(hits))
    elif a.cmd == "show":
        d = kb.docs.get(a.doc_id)
        if not d:
            sys.exit(f"Unknown document: {a.doc_id}")
        print(d.body)
    elif a.cmd == "list":
        for d in kb.docs.values():
            print(f"{d.id:32} {d.topic:14} {d.verified:10} {d.title}")
    elif a.cmd == "export":
        print(f"Wrote {export(kb)}")
    else:
        hits, total = run_eval(kb, a.k)
        sys.exit(0 if hits == total else 1)


if __name__ == "__main__":
    main()
